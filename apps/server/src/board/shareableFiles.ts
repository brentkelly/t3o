/** The temp roots, as realpaths: `os.tmpdir()`, `$TMPDIR`, `/tmp`, `/var/tmp`. */
const TEMP_ROOT_CANDIDATES = (): ReadonlyArray<string> =>
  [NodeOS.tmpdir(), process.env.TMPDIR, "/tmp", "/var/tmp"].filter(
    (root): root is string => root !== undefined && root.length > 0,
  );

const shareableTempRoots = Effect.fn("shareableFiles.tempRoots")(function* () {
  const fs = yield* FileSystem.FileSystem;
  const roots: Array<string> = [];
  for (const root of TEMP_ROOT_CANDIDATES()) {
    const real = yield* fs.realPath(root).pipe(Effect.option);
    if (Option.isSome(real) && !roots.includes(real.value)) roots.push(real.value);
  }
  return roots;
});

export interface ShareableContext {
  readonly mode: BoardShareableFilesMode;
  /** The calling thread's checkout; its paths are the repository's, skipped silently. */
  readonly checkoutRoot: string | null;
  /** The server's chat attachments dir: accepted by `explicit` only. */
  readonly attachmentsDir: string | null;
  /** Overrides for tests; defaults to the real temp roots and this process's uid. */
  readonly tempRoots?: ReadonlyArray<string> | undefined;
  readonly uid?: number | null | undefined;
}

type Collected =
  | {
      readonly kind: "file";
      readonly path: string;
      readonly sourcePath: string;
      readonly real: string;
      readonly name: string;
      readonly mimeType: string;
      readonly bytes: Uint8Array;
    }
  | {
      readonly kind: "directory";
      readonly path: string;
      readonly sourcePath: string;
      readonly real: string;
      readonly name: string;
      readonly members: ReadonlyArray<TarMember>;
      readonly sizeBytes: number;
      /** Member source paths too long for ustar: left out of the archive and its hash. */
      readonly skipped: ReadonlyArray<string>;
    }
  | Extract<BoardShareableItem, { readonly kind: "refused" }>;

const refuse = (
  path: string,
  reason: BoardShareableRefusalReason,
  message: string,
): Extract<BoardShareableItem, { readonly kind: "refused" }> => ({
  kind: "refused",
  path,
  reason,
  message,
});

const COPY_HINT = "copy it into your scratchpad or temp dir, then cite or attach the copy";
const MIB = 1024 * 1024;

const collectOne = Effect.fn("shareableFiles.collect")(function* (
  cited: string,
  context: ShareableContext,
) {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const tempRoots = context.tempRoots ?? (yield* shareableTempRoots());
  const uid =
    context.uid === undefined
      ? typeof process.getuid === "function"
        ? process.getuid()
        : null
      : context.uid;
  const sourcePath = cited.startsWith("~/") ? path.join(NodeOS.homedir(), cited.slice(2)) : cited;
  if (!path.isAbsolute(sourcePath)) {
    return refuse(cited, "not-absolute", `'${cited}' is not an absolute path.`);
  }
  const resolved = path.resolve(sourcePath);
  if (context.checkoutRoot !== null) {
    const checkout = yield* fs
      .realPath(context.checkoutRoot)
      .pipe(Effect.orElseSucceed(() => context.checkoutRoot as string));
    const lexical = path.resolve(context.checkoutRoot);
    const realCandidate = yield* fs.realPath(resolved).pipe(Effect.orElseSucceed(() => resolved));
    if (
      realCandidate === checkout ||
      resolved === lexical ||
      isUnderRoot(path, resolved, [lexical]) ||
      isUnderRoot(path, realCandidate, [checkout])
    ) {
      return refuse(cited, "in-checkout", `'${cited}' is in the repository checkout.`);
    }
  }
  const real = yield* fs.realPath(resolved).pipe(Effect.option);
  if (Option.isNone(real)) {
    // Lexically too: a gone path has no realpath, and `/tmp` may itself be a link.
    const lexicalRoots =
      context.tempRoots === undefined ? [...tempRoots, ...TEMP_ROOT_CANDIDATES()] : tempRoots;
    const underTemp = isUnderRoot(path, resolved, lexicalRoots);
    return underTemp
      ? refuse(
          cited,
          "missing",
          `'${cited}' no longer exists (the scratchpad was probably wiped), so the builder can't get it. Recreate it and re-run.`,
        )
      : refuse(cited, "not-found", `'${cited}' does not exist.`);
  }
  if (real.value.startsWith("/proc/") || real.value === "/proc") {
    return refuse(cited, "not-regular", `'${cited}' is not a regular file.`);
  }
  const roots =
    context.mode === "explicit" && context.attachmentsDir !== null
      ? [
          ...tempRoots,
          yield* fs
            .realPath(context.attachmentsDir)
            .pipe(Effect.orElseSucceed(() => context.attachmentsDir as string)),
        ]
      : tempRoots;
  if (!isUnderRoot(path, real.value, roots)) {
    return refuse(
      cited,
      "outside-allowlist",
      `'${cited}' is outside the temp folders, so it can't be shared and won't exist for the builder: ${COPY_HINT}.`,
    );
  }
  const info = yield* fs.stat(real.value).pipe(Effect.option);
  if (Option.isNone(info)) return refuse(cited, "not-found", `'${cited}' does not exist.`);
  const owned = (fileUid: Option.Option<number>) =>
    uid === null || Option.isNone(fileUid) || fileUid.value === uid;
  if (!owned(info.value.uid)) {
    return refuse(cited, "not-owned", `'${cited}' belongs to another user, so it is not shared.`);
  }
  if (info.value.type === "File") {
    const size = Number(info.value.size);
    if (size > SHAREABLE_ITEM_MAX_BYTES) {
      return refuse(
        cited,
        "too-large",
        `'${cited}' is ${Math.ceil(size / MIB)} MiB; shared files are limited to ${SHAREABLE_ITEM_MAX_BYTES / MIB} MiB.`,
      );
    }
    const bytes = yield* fs.readFile(real.value);
    const name = path.basename(resolved);
    return {
      kind: "file",
      path: cited,
      sourcePath: resolved,
      real: real.value,
      name,
      mimeType: Option.getOrElse(Mime.getType(name), () => "application/octet-stream"),
      bytes,
    } satisfies Collected;
  }
  if (info.value.type !== "Directory") {
    return refuse(cited, "not-regular", `'${cited}' is not a regular file or directory.`);
  }
  if (isTempRootOrChild(path, real.value, tempRoots)) {
    return refuse(
      cited,
      "temp-root",
      `'${cited}' is a temp folder itself or one directly inside it, which can hold other sessions' files; cite a directory deeper down.`,
    );
  }
  // Walk the tree: regular files only, a symlink kept only when its target passes the same
  // rule, and nothing past the member cap.
  const base = path.basename(resolved);
  const members: Array<TarMember> = [];
  const skipped: Array<string> = [];
  let total = 0;
  let overflow: BoardShareableRefusalReason | null = null;
  const walk: (dir: string, relative: string) => Effect.Effect<void> = Effect.fn(
    "shareableFiles.walk",
  )(function* (dir: string, relative: string) {
    const entries = yield* fs.readDirectory(dir).pipe(Effect.orElseSucceed(() => []));
    for (const entry of [...entries].sort()) {
      if (overflow !== null) return;
      const full = path.join(dir, entry);
      const rel = relative === "" ? entry : `${relative}/${entry}`;
      const link = yield* fs.lstat(full).pipe(Effect.option);
      if (Option.isNone(link)) continue;
      let target = full;
      let stat = link.value;
      if (link.value.type === "SymbolicLink") {
        const linkReal = yield* fs.realPath(full).pipe(Effect.option);
        if (Option.isNone(linkReal) || !isUnderRoot(path, linkReal.value, tempRoots)) continue;
        const linkStat = yield* fs.stat(linkReal.value).pipe(Effect.option);
        // A linked directory is skipped rather than followed: it could loop.
        if (Option.isNone(linkStat) || linkStat.value.type !== "File") continue;
        target = linkReal.value;
        stat = linkStat.value;
      }
      if (!owned(stat.uid)) continue;
      if (stat.type === "Directory") {
        yield* walk(full, rel);
        continue;
      }
      if (stat.type !== "File") continue;
      if (splitUstarPath(`${base}/${rel}`) === null) {
        skipped.push(full);
        continue;
      }
      if (members.length >= SHAREABLE_DIRECTORY_MAX_MEMBERS) {
        overflow = "too-many-members";
        return;
      }
      total += Number(stat.size);
      if (total > SHAREABLE_ITEM_MAX_BYTES) {
        overflow = "too-large";
        return;
      }
      const bytes = yield* fs.readFile(target).pipe(Effect.option);
      if (Option.isSome(bytes)) members.push({ path: `${base}/${rel}`, bytes: bytes.value });
    }
  });
  yield* walk(real.value, "");
  if (overflow === "too-many-members") {
    return refuse(
      cited,
      "too-many-members",
      `'${cited}' has more than ${SHAREABLE_DIRECTORY_MAX_MEMBERS} files; cite a smaller directory.`,
    );
  }
  if (overflow === "too-large") {
    return refuse(
      cited,
      "too-large",
      `'${cited}' holds more than ${SHAREABLE_ITEM_MAX_BYTES / MIB} MiB; cite a smaller directory.`,
    );
  }
  return {
    kind: "directory",
    path: cited,
    sourcePath: resolved,
    real: real.value,
    name: `${base}.tar.gz`,
    members,
    sizeBytes: total,
    skipped,
  } satisfies Collected;
});

const toItem = (collected: Collected): BoardShareableItem => {
  switch (collected.kind) {
    case "refused":
      return collected;
    case "file":
      return {
        kind: "file",
        path: collected.path,
        sourcePath: collected.sourcePath,
        name: collected.name,
        mimeType: collected.mimeType,
        sizeBytes: collected.bytes.length,
        contentHash: sha256(collected.bytes),
      };
    case "directory":
      return {
        kind: "directory",
        path: collected.path,
        sourcePath: collected.sourcePath,
        name: collected.name,
        mimeType: "application/gzip",
        sizeBytes: collected.sizeBytes,
        memberCount: collected.members.length,
        contentHash: directoryContentHash(collected.members),
      };
  }
};

const GLOB = /[*?]/;
/** Matches one glob may attach; more is a directory's job. */
const SHAREABLE_GLOB_MAX_MATCHES = 20;

const globPattern = (glob: string): RegExp => {
  const escaped = glob.replace(/[.+^${}()|[\]\\]/g, "\\$&");
  return new RegExp("^" + escaped.replace(/\*/g, "[^/]*").replace(/\?/g, "[^/]") + "$");
};

/**
 * A cited glob's matches, when only its last segment is a pattern and its directory is under a
 * temp root (or the chat dir for an explicit attach). Null when it is not one to expand.
 */
const expandGlob = Effect.fn("shareableFiles.expandGlob")(function* (
  cited: string,
  context: ShareableContext,
) {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const expanded = cited.startsWith("~/") ? path.join(NodeOS.homedir(), cited.slice(2)) : cited;
  const dir = path.dirname(expanded);
  const pattern = path.basename(expanded);
  if (!GLOB.test(pattern) || GLOB.test(dir) || !path.isAbsolute(dir)) return null;
  const tempRoots = context.tempRoots ?? (yield* shareableTempRoots());
  const real = yield* fs.realPath(dir).pipe(Effect.option);
  if (Option.isNone(real)) return null;
  const roots =
    context.mode === "explicit" && context.attachmentsDir !== null
      ? [...tempRoots, context.attachmentsDir]
      : tempRoots;
  if (!roots.includes(real.value) && !isUnderRoot(path, real.value, roots)) return null;
  const matcher = globPattern(pattern);
  const entries = yield* fs.readDirectory(real.value).pipe(Effect.orElseSucceed(() => []));
  return [...entries]
    .filter((entry) => matcher.test(entry))
    .sort()
    .map((entry) => path.join(dir, entry));
});

/**
 * What each cited path is, with its hash, without carrying bytes: each item is reduced to its
 * hash as it is read, so one item's bytes are live at a time. A glob in a path's last segment
 * expands to its matches, each reported under the cited glob. A file inside another cited
 * directory travels in that archive, so it is not offered on its own.
 */
export const inspectShareableFiles = Effect.fn("shareableFiles.inspect")(function* (
  paths: ReadonlyArray<string>,
  context: ShareableContext,
) {
  const path = yield* Path.Path;
  const inspected: Array<{ readonly item: BoardShareableItem; readonly real: string | null }> = [];
  const collect = (target: string, cited: string) =>
    collectOne(target, context).pipe(
      Effect.orElseSucceed(() => refuse(cited, "not-found", `'${cited}' could not be read.`)),
      Effect.map((collected) => {
        if (collected.kind === "refused") {
          inspected.push({ item: { ...collected, path: cited }, real: null });
          return;
        }
        inspected.push({ item: { ...toItem(collected), path: cited }, real: collected.real });
        if (collected.kind === "directory") {
          for (const member of collected.skipped) {
            inspected.push({
              item: refuse(
                member,
                "not-archivable",
                `'${member}' was left out of ${collected.name}: its path is too long for the archive. Rename it shorter and re-run.`,
              ),
              real: null,
            });
          }
        }
      }),
    );
  for (const cited of paths) {
    const matches = yield* expandGlob(cited, context).pipe(Effect.orElseSucceed(() => null));
    if (matches === null) {
      yield* collect(cited, cited);
    } else if (matches.length === 0) {
      inspected.push({
        item: refuse(cited, "not-found", `'${cited}' matches no files.`),
        real: null,
      });
    } else if (matches.length > SHAREABLE_GLOB_MAX_MATCHES) {
      inspected.push({
        item: refuse(
          cited,
          "too-many-members",
          `'${cited}' matches ${matches.length} files, more than ${SHAREABLE_GLOB_MAX_MATCHES}; put them in one directory and cite that.`,
        ),
        real: null,
      });
    } else {
      for (const match of matches) yield* collect(match, cited);
    }
  }
  const directories = inspected.flatMap((entry) =>
    entry.item.kind === "directory" && entry.real !== null ? [entry.real] : [],
  );
  return inspected.map(({ item, real }): BoardShareableItem => {
    if (item.kind === "file" && real !== null && isUnderRoot(path, real, directories)) {
      return refuse(
        item.path,
        "inside-cited-directory",
        `'${item.path}' travels inside a cited directory's archive.`,
      );
    }
    return item;
  });
});

/** One item's bytes: a file's own, or its directory's `.tar.gz`. The allowlist is checked
    again here, and the hash is recomputed from what was read. */
export const readShareableItem = Effect.fn("shareableFiles.read")(function* (
  sourcePath: string,
  context: ShareableContext,
) {
  const collected = yield* collectOne(sourcePath, { ...context, checkoutRoot: null });
  if (collected.kind === "refused") return collected;
  if (collected.kind === "file") {
    return {
      name: collected.name,
      mimeType: collected.mimeType,
      bytes: collected.bytes,
      contentHash: sha256(collected.bytes),
    } satisfies Omit<BoardReadShareableFileResult, "contentBase64"> & { bytes: Uint8Array };
  }
  const archive = writeTarGz(collected.members);
  return {
    name: collected.name,
    mimeType: "application/gzip",
    bytes: archive.bytes,
    contentHash: directoryContentHash(collected.members),
    memberCount: collected.members.length - archive.dropped.length,
  } satisfies Omit<BoardReadShareableFileResult, "contentBase64"> & { bytes: Uint8Array };
});
