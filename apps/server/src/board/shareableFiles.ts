/**
 * T3o: the files a plan cites, made shareable with its builder (T3O-138). A planner's scratch
 * files live in a session-scoped temp dir, often on another machine, so the plan tools copy
 * them onto the card as attachments. Only the caller's own regular files under a temp root can
 * leave the machine: an allowlist, checked on the realpath, never a denylist.
 */
