// @effect-diagnostics nodeBuiltinImport:off - sha256, gzip and the temp/home dirs have no Effect service.
/**
 * T3o: the files a plan cites, made shareable with its builder (T3O-138). A planner's scratch
 * files live in a session-scoped temp dir, often on another machine, so the plan tools copy
 * them onto the card as attachments. Only the caller's own regular files under a temp root can
 * leave the machine: an allowlist, checked on the realpath, never a denylist.
 */
import * as NodeCrypto from "node:crypto";
import * as NodeOs from "node:os";
import * as NodeZlib from "node:zlib";

import type {
  BoardReadShareableFileResult,
  BoardShareableFilesMode,
  BoardShareableItem,
  BoardShareableRefusalReason,
} from "@t3tools/contracts";
import * as Effect from "effect/Effect";
import * as FileSystem from "effect/FileSystem";
import * as Mime from "effect/http/Mime";
import * as Option from "effect/Option";
import * as Path from "effect/Path";

export const SHAREABLE_ITEM_MAX_BYTES = 20 * 1024 * 1024;
/** What one plan-tool call reads in total: the relay's 60 s timeout covers the whole call. */
export const SHAREABLE_CALL_MAX_BYTES = 40 * 1024 * 1024;
export const SHAREABLE_DIRECTORY_MAX_MEMBERS = 200;

export const ATTACHED_FILES_OPEN = "<!-- t3o:attached-files -->";
export const ATTACHED_FILES_CLOSE = "<!-- /t3o:attached-files -->";

// ── Pure ───────────────────────────────────────────────────────────────

/** A generated footer, removed so neither an edit nor a scan ever sees it. */
export function stripAttachedFilesFooter(body: string): string {
  const open = body.indexOf(ATTACHED_FILES_OPEN);
  if (open === -1) return body;
  const close = body.indexOf(ATTACHED_FILES_CLOSE, open);
  const after = close === -1 ? "" : body.slice(close + ATTACHED_FILES_CLOSE.length);
  return (body.slice(0, open).replace(/\s+$/, "") + after.replace(/^\s+/, "\n")).replace(
    /\s+$/,
    "\n",
  );
}

export interface AttachedFileFooterItem {
  readonly name: string;
  readonly sourcePath: string;
  readonly memberCount?: number | undefined;
}

/** The footer mapping each cited path to the attachment that carries it, or "" for none. */
export function renderAttachedFilesFooter(input: {
  readonly items: ReadonlyArray<AttachedFileFooterItem>;
  /** In a split the files sit on the parent card, not the child the plan becomes. */
  readonly onCardKey?: string | undefined;
}): string {
  if (input.items.length === 0) return "";
  const on = input.onCardKey === undefined ? "" : ` (on ${input.onCardKey})`;
  const lines = input.items.map((item) => {
    const archive =
      item.memberCount === undefined
        ? ""
        : `; ${item.memberCount} files; unpack with \`tar xzf <its path> -C <your scratch dir>\``;
    return `- \`${item.name}\`${on} (from \`${item.sourcePath}\`${archive})`;
  });
  return [
    ATTACHED_FILES_OPEN,
    "## Attached files",
    "",
    "Generated by the board; edits here are discarded. Each is a card attachment: read it from board_get_card_context `attachments` (or `inheritedAttachments`), never from the original path.",
    "",
    ...lines,
    ATTACHED_FILES_CLOSE,
  ].join("\n");
}

/** `body` with its footer regenerated. */
export function withAttachedFilesFooter(
  body: string,
  footer: Parameters<typeof renderAttachedFilesFooter>[0],
): string {
  const stripped = stripAttachedFilesFooter(body);
  const rendered = renderAttachedFilesFooter(footer);
  if (rendered === "") return stripped;
  return `${stripped.replace(/\s+$/, "")}\n\n${rendered}\n`;
}

const PATH_START = /^(?:~\/|\/(?!\/)|[A-Za-z]:[\\/])/;
const BARE_PATH = /(?:^|[\s("'[<=])((?:~\/|\/(?!\/)|[A-Za-z]:[\\/])[^\s`'"<>()[\]{}|*]+)/g;

function cleanCitedPath(raw: string): string | null {
  let value = raw.trim();
  value = value.replace(/[.,;:!?]+$/, "");
  value = value.replace(/:\d+(?::\d+)?$/, "");
  value = value.replace(/[.,;:!?]+$/, "");
  // A bare root ("/", "~/", "C:\") names nothing worth sharing.
  if (!PATH_START.test(value) || /^(?:~\/|\/|[A-Za-z]:[\\/])$/.test(value)) return null;
  return value;
}

/**
 * Absolute POSIX, `~/` and Windows drive paths a text cites: in backticks (spaces allowed),
 * as a markdown link target, or bare. A trailing `:line[:col]` and punctuation are dropped,
 * and the generated footer is ignored. In order of first mention, without repeats.
 */
export function extractCitedPaths(text: string): ReadonlyArray<string> {
  const body = stripAttachedFilesFooter(text);
  const found: Array<string> = [];
  const add = (raw: string) => {
    const cleaned = cleanCitedPath(raw);
    if (cleaned !== null && !found.includes(cleaned)) found.push(cleaned);
  };
  // Fenced blocks and inline code are read span by span, so a path with a space survives.
  const rest = body.replace(/`([^`\n]+)`/g, (_match, inner: string) => {
    if (PATH_START.test(inner.trim())) add(inner);
    else for (const match of inner.matchAll(BARE_PATH)) add(match[1] ?? "");
    return " ";
  });
  for (const match of rest.matchAll(BARE_PATH)) add(match[1] ?? "");
  return found;
}

/** Is `real` strictly under one of `roots`? All realpaths. */
export function isUnderRoot(path: Path.Path, real: string, roots: ReadonlyArray<string>): boolean {
  return roots.some((root) => {
    const relative = path.relative(root, real);
    return relative !== "" && !relative.startsWith("..") && !path.isAbsolute(relative);
  });
}

/** A temp root itself, or a direct child of one (`/tmp/claude-1101` holds every session's
    scratchpad): never archived whole. */
export function isTempRootOrChild(
  path: Path.Path,
  real: string,
  roots: ReadonlyArray<string>,
): boolean {
  return roots.some((root) => real === root || path.dirname(real) === root);
}

export interface TarMember {
  /** Forward-slash relative path inside the archive. */
  readonly path: string;
  readonly bytes: Uint8Array;
}

const utf8 = new TextEncoder();

function writeField(header: Uint8Array, offset: number, length: number, value: string): void {
  const bytes = utf8.encode(value);
  header.set(bytes.subarray(0, length), offset);
}

function octal(value: number, length: number): string {
  return value.toString(8).padStart(length - 1, "0");
}

/** ustar's name/prefix split, or null when the path fits neither. */
function splitUstarPath(path: string): { readonly name: string; readonly prefix: string } | null {
  if (utf8.encode(path).length <= 100) return { name: path, prefix: "" };
  for (let index = path.indexOf("/"); index !== -1; index = path.indexOf("/", index + 1)) {
    const prefix = path.slice(0, index);
    const name = path.slice(index + 1);
    if (utf8.encode(prefix).length <= 155 && utf8.encode(name).length <= 100 && name !== "") {
      return { name, prefix };
    }
  }
  return null;
}

/**
 * A deterministic `.tar.gz`: members sorted, mtime 0, uid/gid 0, mode 0644, so the same files
 * always make the same bytes. A member whose path ustar cannot hold is dropped and reported.
 */
export function writeTarGz(members: ReadonlyArray<TarMember>): {
  readonly bytes: Uint8Array;
  readonly dropped: ReadonlyArray<string>;
} {
  const sorted = [...members].sort((left, right) =>
    left.path < right.path ? -1 : left.path > right.path ? 1 : 0,
  );
  const blocks: Array<Uint8Array> = [];
  const dropped: Array<string> = [];
  for (const member of sorted) {
    const split = splitUstarPath(member.path);
    if (split === null) {
      dropped.push(member.path);
      continue;
    }
    const header = new Uint8Array(512);
    writeField(header, 0, 100, split.name);
    writeField(header, 100, 8, `${octal(0o644, 8)}\0`);
    writeField(header, 108, 8, `${octal(0, 8)}\0`);
    writeField(header, 116, 8, `${octal(0, 8)}\0`);
    writeField(header, 124, 12, `${octal(member.bytes.length, 12)}\0`);
    writeField(header, 136, 12, `${octal(0, 12)}\0`);
    writeField(header, 148, 8, "        ");
    writeField(header, 156, 1, "0");
    writeField(header, 257, 6, "ustar\0");
    writeField(header, 263, 2, "00");
    writeField(header, 345, 155, split.prefix);
    const checksum = header.reduce((sum, byte) => sum + byte, 0);
    writeField(header, 148, 8, `${octal(checksum, 7)}\0 `);
    blocks.push(header, member.bytes);
    const pad = (512 - (member.bytes.length % 512)) % 512;
    if (pad > 0) blocks.push(new Uint8Array(pad));
  }
  blocks.push(new Uint8Array(1024));
  const tar = Buffer.concat(blocks);
  return { bytes: new Uint8Array(NodeZlib.gzipSync(tar)), dropped };
}

const sha256 = (bytes: Uint8Array | string): string =>
  NodeCrypto.createHash("sha256").update(bytes).digest("hex");

/** A directory's hash: its sorted member paths and their contents, never the archive bytes. */
export function directoryContentHash(members: ReadonlyArray<TarMember>): string {
  const lines = [...members]
    .sort((left, right) => (left.path < right.path ? -1 : left.path > right.path ? 1 : 0))
    .map((member) => `${member.path}\0${sha256(member.bytes)}\n`);
  return sha256(lines.join(""));
}

// ── Effectful ──────────────────────────────────────────────────────────

/** The temp roots, as realpaths: `os.tmpdir()`, `$TMPDIR`, `/tmp`, `/var/tmp`. */
const TEMP_ROOT_CANDIDATES = (): ReadonlyArray<string> =>
  [NodeOs.tmpdir(), process.env.TMPDIR, "/tmp", "/var/tmp"].filter(
    (root): root is string => root !== undefined && root.length > 0,
  );

export const shareableTempRoots = Effect.fn("shareableFiles.tempRoots")(function* () {
  const fs = yield* FileSystem.FileSystem;
  const roots: Array<string> = [];
  for (const root of TEMP_ROOT_CANDIDATES()) {
    const real = yield* fs.realPath(root).pipe(Effect.option);
    if (Option.isSome(real) && !roots.includes(real.value)) roots.push(real.value);
  }
  return roots;
});

export interface ShareableContext {
  readonly mode: BoardShareableFilesMode;
  /** The calling thread's checkout; its paths are the repository's, skipped silently. */
  readonly checkoutRoot: string | null;
  /** The server's chat attachments dir: accepted by `explicit` only. */
  readonly attachmentsDir: string | null;
  /** Overrides for tests; defaults to the real temp roots and this process's uid. */
  readonly tempRoots?: ReadonlyArray<string> | undefined;
  readonly uid?: number | null | undefined;
}

type Collected =
  | {
      readonly kind: "file";
      readonly path: string;
      readonly sourcePath: string;
      readonly real: string;
      readonly name: string;
      readonly mimeType: string;
      readonly bytes: Uint8Array;
    }
  | {
      readonly kind: "directory";
      readonly path: string;
      readonly sourcePath: string;
      readonly real: string;
      readonly name: string;
      readonly members: ReadonlyArray<TarMember>;
      readonly sizeBytes: number;
    }
  | Extract<BoardShareableItem, { readonly kind: "refused" }>;

const refuse = (
  path: string,
  reason: BoardShareableRefusalReason,
  message: string,
): Extract<BoardShareableItem, { readonly kind: "refused" }> => ({
  kind: "refused",
  path,
  reason,
  message,
});

const COPY_HINT = "copy it into your scratchpad or temp dir, then cite or attach the copy";
const MIB = 1024 * 1024;

const collectOne = Effect.fn("shareableFiles.collect")(function* (
  cited: string,
  context: ShareableContext,
) {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const tempRoots = context.tempRoots ?? (yield* shareableTempRoots());
  const uid =
    context.uid === undefined
      ? typeof process.getuid === "function"
        ? process.getuid()
        : null
      : context.uid;
  const sourcePath = cited.startsWith("~/") ? path.join(NodeOs.homedir(), cited.slice(2)) : cited;
  if (!path.isAbsolute(sourcePath)) {
    return refuse(cited, "not-absolute", `'${cited}' is not an absolute path.`);
  }
  const resolved = path.resolve(sourcePath);
  if (context.checkoutRoot !== null) {
    const checkout = yield* fs
      .realPath(context.checkoutRoot)
      .pipe(Effect.orElseSucceed(() => context.checkoutRoot as string));
    const lexical = path.resolve(context.checkoutRoot);
    const realCandidate = yield* fs.realPath(resolved).pipe(Effect.orElseSucceed(() => resolved));
    if (
      realCandidate === checkout ||
      resolved === lexical ||
      isUnderRoot(path, resolved, [lexical]) ||
      isUnderRoot(path, realCandidate, [checkout])
    ) {
      return refuse(cited, "in-checkout", `'${cited}' is in the repository checkout.`);
    }
  }
  const real = yield* fs.realPath(resolved).pipe(Effect.option);
  if (Option.isNone(real)) {
    // Lexically too: a gone path has no realpath, and `/tmp` may itself be a link.
    const lexicalRoots =
      context.tempRoots === undefined ? [...tempRoots, ...TEMP_ROOT_CANDIDATES()] : tempRoots;
    const underTemp = isUnderRoot(path, resolved, lexicalRoots);
    return underTemp
      ? refuse(
          cited,
          "missing",
          `'${cited}' no longer exists (the scratchpad was probably wiped), so the builder can't get it. Recreate it and re-run.`,
        )
      : refuse(cited, "not-found", `'${cited}' does not exist.`);
  }
  if (real.value.startsWith("/proc/") || real.value === "/proc") {
    return refuse(cited, "not-regular", `'${cited}' is not a regular file.`);
  }
  const roots =
    context.mode === "explicit" && context.attachmentsDir !== null
      ? [
          ...tempRoots,
          yield* fs
            .realPath(context.attachmentsDir)
            .pipe(Effect.orElseSucceed(() => context.attachmentsDir as string)),
        ]
      : tempRoots;
  if (!isUnderRoot(path, real.value, roots)) {
    return refuse(
      cited,
      "outside-allowlist",
      `'${cited}' is outside the temp folders, so it can't be shared and won't exist for the builder: ${COPY_HINT}.`,
    );
  }
  const info = yield* fs.stat(real.value).pipe(Effect.option);
  if (Option.isNone(info)) return refuse(cited, "not-found", `'${cited}' does not exist.`);
  const owned = (fileUid: Option.Option<number>) =>
    uid === null || Option.isNone(fileUid) || fileUid.value === uid;
  if (!owned(info.value.uid)) {
    return refuse(cited, "not-owned", `'${cited}' belongs to another user, so it is not shared.`);
  }
  if (info.value.type === "File") {
    const size = Number(info.value.size);
    if (size > SHAREABLE_ITEM_MAX_BYTES) {
      return refuse(
        cited,
        "too-large",
        `'${cited}' is ${Math.ceil(size / MIB)} MiB; shared files are limited to ${SHAREABLE_ITEM_MAX_BYTES / MIB} MiB.`,
      );
    }
    const bytes = yield* fs.readFile(real.value);
    const name = path.basename(resolved);
    return {
      kind: "file",
      path: cited,
      sourcePath: resolved,
      real: real.value,
      name,
      mimeType: Option.getOrElse(Mime.getType(name), () => "application/octet-stream"),
      bytes,
    } satisfies Collected;
  }
  if (info.value.type !== "Directory") {
    return refuse(cited, "not-regular", `'${cited}' is not a regular file or directory.`);
  }
  if (isTempRootOrChild(path, real.value, tempRoots)) {
    return refuse(
      cited,
      "temp-root",
      `'${cited}' is a temp folder itself or one directly inside it, which can hold other sessions' files; cite a directory deeper down.`,
    );
  }
  // Walk the tree: regular files only, a symlink kept only when its target passes the same
  // rule, and nothing past the member cap.
  const base = path.basename(resolved);
  const members: Array<TarMember> = [];
  let total = 0;
  let overflow: BoardShareableRefusalReason | null = null;
  const walk = (dir: string, relative: string): Effect.Effect<void, never> =>
    Effect.gen(function* () {
      const entries = yield* fs.readDirectory(dir).pipe(Effect.orElseSucceed(() => []));
      for (const entry of [...entries].sort()) {
        if (overflow !== null) return;
        const full = path.join(dir, entry);
        const rel = relative === "" ? entry : `${relative}/${entry}`;
        const link = yield* fs.lstat(full).pipe(Effect.option);
        if (Option.isNone(link)) continue;
        let target = full;
        let stat = link.value;
        if (link.value.type === "SymbolicLink") {
          const linkReal = yield* fs.realPath(full).pipe(Effect.option);
          if (Option.isNone(linkReal) || !isUnderRoot(path, linkReal.value, tempRoots)) continue;
          const linkStat = yield* fs.stat(linkReal.value).pipe(Effect.option);
          // A linked directory is skipped rather than followed: it could loop.
          if (Option.isNone(linkStat) || linkStat.value.type !== "File") continue;
          target = linkReal.value;
          stat = linkStat.value;
        }
        if (!owned(stat.uid)) continue;
        if (stat.type === "Directory") {
          yield* walk(full, rel);
          continue;
        }
        if (stat.type !== "File") continue;
        if (members.length >= SHAREABLE_DIRECTORY_MAX_MEMBERS) {
          overflow = "too-many-members";
          return;
        }
        total += Number(stat.size);
        if (total > SHAREABLE_ITEM_MAX_BYTES) {
          overflow = "too-large";
          return;
        }
        const bytes = yield* fs.readFile(target).pipe(Effect.option);
        if (Option.isSome(bytes)) members.push({ path: `${base}/${rel}`, bytes: bytes.value });
      }
    });
  yield* walk(real.value, "");
  if (overflow === "too-many-members") {
    return refuse(
      cited,
      "too-many-members",
      `'${cited}' has more than ${SHAREABLE_DIRECTORY_MAX_MEMBERS} files; cite a smaller directory.`,
    );
  }
  if (overflow === "too-large") {
    return refuse(
      cited,
      "too-large",
      `'${cited}' holds more than ${SHAREABLE_ITEM_MAX_BYTES / MIB} MiB; cite a smaller directory.`,
    );
  }
  return {
    kind: "directory",
    path: cited,
    sourcePath: resolved,
    real: real.value,
    name: `${base}.tar.gz`,
    members,
    sizeBytes: total,
  } satisfies Collected;
});

const toItem = (collected: Collected): BoardShareableItem => {
  switch (collected.kind) {
    case "refused":
      return collected;
    case "file":
      return {
        kind: "file",
        path: collected.path,
        sourcePath: collected.sourcePath,
        name: collected.name,
        mimeType: collected.mimeType,
        sizeBytes: collected.bytes.length,
        contentHash: sha256(collected.bytes),
      };
    case "directory":
      return {
        kind: "directory",
        path: collected.path,
        sourcePath: collected.sourcePath,
        name: collected.name,
        mimeType: "application/gzip",
        sizeBytes: collected.sizeBytes,
        memberCount: collected.members.length,
        contentHash: directoryContentHash(collected.members),
      };
  }
};

/**
 * What each cited path is, with its hash, without carrying bytes. A file inside another cited
 * directory travels in that archive, so it is not offered on its own.
 */
export const inspectShareableFiles = Effect.fn("shareableFiles.inspect")(function* (
  paths: ReadonlyArray<string>,
  context: ShareableContext,
) {
  const path = yield* Path.Path;
  const collected: Array<Collected> = [];
  for (const cited of paths) {
    collected.push(
      yield* collectOne(cited, context).pipe(
        Effect.catch(() =>
          Effect.succeed(refuse(cited, "not-found", `'${cited}' could not be read.`)),
        ),
      ),
    );
  }
  const directories = collected.flatMap((item) => (item.kind === "directory" ? [item.real] : []));
  return collected.map((item): BoardShareableItem => {
    if (item.kind === "file" && isUnderRoot(path, item.real, directories)) {
      return refuse(
        item.path,
        "inside-cited-directory",
        `'${item.path}' travels inside a cited directory's archive.`,
      );
    }
    return toItem(item);
  });
});

/** One item's bytes: a file's own, or its directory's `.tar.gz`. The allowlist is checked
    again here, and the hash is recomputed from what was read. */
export const readShareableItem = Effect.fn("shareableFiles.read")(function* (
  sourcePath: string,
  context: ShareableContext,
) {
  const collected = yield* collectOne(sourcePath, { ...context, checkoutRoot: null });
  if (collected.kind === "refused") return collected;
  if (collected.kind === "file") {
    return {
      name: collected.name,
      mimeType: collected.mimeType,
      bytes: collected.bytes,
      contentHash: sha256(collected.bytes),
    } satisfies Omit<BoardReadShareableFileResult, "contentBase64"> & { bytes: Uint8Array };
  }
  const archive = writeTarGz(collected.members);
  return {
    name: collected.name,
    mimeType: "application/gzip",
    bytes: archive.bytes,
    contentHash: directoryContentHash(collected.members),
    memberCount: collected.members.length - archive.dropped.length,
  } satisfies Omit<BoardReadShareableFileResult, "contentBase64"> & { bytes: Uint8Array };
});
